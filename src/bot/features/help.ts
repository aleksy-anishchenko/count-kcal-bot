import { Composer } from 'grammy';
import type { BotContext } from '../context.ts';

const HELP_TEXT = `Я считаю калории. Напиши, что съел:
• «овсянка 80 г на молоке, банан, кофе с молоком»
• «банка тунца, 3 варёных яйца»
Граммовки необязательны — если их нет, порцию оценю сам.

Или пришли фото: блюдо, таблицу калорийности на упаковке или штрихкод — снимай крупно. Подпись помогает: «это 300 г», «съел половину». Несколько фото одним сообщением — одна запись.

Команды:
/today — что съел сегодня
/week — сводка за 7 дней
/undo — удалить последнюю запись
/clear — удалить все записи за сегодня`;

export const helpFeature = new Composer<BotContext>();

helpFeature.command(['start', 'help'], (ctx) => ctx.reply(HELP_TEXT));
