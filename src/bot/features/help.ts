import { Composer } from 'grammy';
import type { BotContext } from '../context.ts';

const HELP_TEXT = `Я считаю калории. Просто напиши, что съел:
• «завтрак: овсянка 80 г на молоке, банан, кофе с молоком»
• «банка тунца, 3 варёных яйца»
Граммовки необязательны — если их нет, порцию оценю сам.
Можно прислать фото: блюдо, упаковку с таблицей калорийности или штрихкод (его и таблицу снимай крупно). Подпись к фото помогает: «это 300 г», «съел половину».
Несколько фото одним сообщением — одна запись (например, упаковка с двух сторон). Мелкий штрихкод лучше прислать файлом: так фото не сжимается.
Если оценить продукт не получилось, вместо числа будет «?», а итог помечу ⚠️ — реальная сумма больше.
Под каждой записью есть кнопка «↩️ Отменить» — она удаляет именно эту запись.

Команды:
/today — что съел сегодня и итог
/week — сводка за 7 дней
/stats — сколько токенов DeepSeek потрачено
/undo — удалить последнюю запись
/clear — удалить все записи за сегодня`;

export const helpFeature = new Composer<BotContext>();

helpFeature.command(['start', 'help'], (ctx) => ctx.reply(HELP_TEXT));
